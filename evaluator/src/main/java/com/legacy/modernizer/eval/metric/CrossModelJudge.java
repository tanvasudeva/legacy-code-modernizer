package com.legacy.modernizer.eval.metric;

import dev.langchain4j.data.message.SystemMessage;
import dev.langchain4j.data.message.UserMessage;
import dev.langchain4j.model.anthropic.AnthropicChatModel;
import dev.langchain4j.model.chat.ChatLanguageModel;
import dev.langchain4j.model.openai.OpenAiChatModel;
import dev.langchain4j.model.openai.OpenAiChatModelName;
import jakarta.annotation.PostConstruct;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Component;

import java.time.Duration;
import java.util.List;
import java.util.Map;

/**
 * Phase 4.6 — Cross-model LLM judge (strategy pattern).
 *
 * <p><b>Problem</b>: using Claude to judge Claude-generated output inflates its
 * score relative to GPT-4o output.  This is a well-documented bias in LLM
 * self-evaluation and the first methodological criticism any ML reviewer raises.
 *
 * <p><b>Solution</b> (consistent with MT-Bench, Chatbot Arena, AlpacaEval):
 * <table>
 *   <tr><th>System being evaluated</th><th>Judge model</th><th>Rationale</th></tr>
 *   <tr><td>{@code multi-agent}</td><td>GPT-4o</td>
 *       <td>Output generated by Claude — must be judged by a different family</td></tr>
 *   <tr><td>{@code single-prompt-gpt4o}</td><td>Claude claude-sonnet-4-6</td>
 *       <td>Output generated by GPT-4o — judged by Claude</td></tr>
 *   <tr><td>{@code single-prompt-claude}</td><td>GPT-4o</td>
 *       <td>Output generated by Claude — same rule as multi-agent</td></tr>
 * </table>
 *
 * <p>The {@code judge_model} value is persisted in {@code eval_metrics.judge_model}
 * so reviewers can verify the evaluation design from the database alone.
 *
 * <p><b>Degraded modes</b> (logged at WARN level):
 * <ul>
 *   <li>Only {@code ANTHROPIC_API_KEY} — Claude judges everything (self-scoring
 *       for multi-agent and claude-baseline, noted in metadata)</li>
 *   <li>Only {@code OPENAI_API_KEY} — GPT-4o judges everything</li>
 *   <li>Neither key — all judge scores return 0.0</li>
 * </ul>
 */
@Component
public class CrossModelJudge {

    private static final Logger log = LoggerFactory.getLogger(CrossModelJudge.class);

    public static final String CLAUDE_MODEL_ID = "claude-sonnet-4-6";
    public static final String GPT4O_MODEL_ID  = "gpt-4o";

    private static final int MAX_OUTPUT_TOKENS = 512;

    private ChatLanguageModel claudeModel;  // judges GPT-4o output
    private ChatLanguageModel gpt4oModel;   // judges Claude output

    /** Result of one cross-model judge call. */
    public record JudgeResult(
            double              score,
            String              judgeModelId,
            Map<String, Object> subScores,
            Map<String, Object> metadata
    ) {}

    @PostConstruct
    void init() {
        String anthropicKey = System.getenv("ANTHROPIC_API_KEY");
        String openaiKey    = System.getenv("OPENAI_API_KEY");

        if (anthropicKey != null && !anthropicKey.isBlank()) {
            claudeModel = AnthropicChatModel.builder()
                    .apiKey(anthropicKey)
                    .modelName(CLAUDE_MODEL_ID)
                    .maxTokens(MAX_OUTPUT_TOKENS)
                    .temperature(0.0)
                    .timeout(Duration.ofSeconds(120))
                    .build();
            log.info("[cross-model-judge] Claude ({}) initialised", CLAUDE_MODEL_ID);
        } else {
            log.warn("[cross-model-judge] ANTHROPIC_API_KEY not set — Claude judge unavailable");
        }

        if (openaiKey != null && !openaiKey.isBlank()) {
            gpt4oModel = OpenAiChatModel.builder()
                    .apiKey(openaiKey)
                    .modelName(OpenAiChatModelName.GPT_4_O)
                    .maxTokens(MAX_OUTPUT_TOKENS)
                    .temperature(0.0)
                    .timeout(Duration.ofSeconds(120))
                    .build();
            log.info("[cross-model-judge] GPT-4o ({}) initialised", GPT4O_MODEL_ID);
        } else {
            log.warn("[cross-model-judge] OPENAI_API_KEY not set — GPT-4o judge unavailable");
        }

        logRoutingTable();
    }

    // ─── Public API ───────────────────────────────────────────────────────────

    /**
     * Judges {@code content} using the correct cross-model judge for {@code systemId}.
     *
     * @param systemId     the system whose output is being evaluated
     *                     ({@code "multi-agent"}, {@code "single-prompt-gpt4o"},
     *                     {@code "single-prompt-claude"})
     * @param content      the code or plan text to evaluate
     * @param systemPrompt the dimension-scoring system prompt
     */
    public JudgeResult judge(String systemId, String content, String systemPrompt) {
        ChatLanguageModel judge   = resolveJudge(systemId);
        String            modelId = resolveJudgeModelId(systemId);

        if (judge == null) {
            log.warn("[cross-model-judge] Judge unavailable for systemId={} modelId={}",
                    systemId, modelId);
            return new JudgeResult(0.0, modelId, Map.of(),
                    Map.of("reason", "judge model unavailable (" + modelId + " key not set)",
                           "judgeModel", modelId));
        }

        try {
            String raw = judge.generate(List.of(
                    SystemMessage.from(systemPrompt),
                    UserMessage.from(content)
            )).content().text();

            Map<String, Object> subScores = LlmJudgeMetric.parseSubScoresStatic(raw);
            double avg = LlmJudgeMetric.computeAverage(subScores);

            log.info("[cross-model-judge] systemId={} judgeModel={} score={}",
                    systemId, modelId, avg);
            return new JudgeResult(avg, modelId, subScores,
                    Map.of("judgeModel", modelId, "system", systemId));

        } catch (Exception e) {
            log.error("[cross-model-judge] Call failed systemId={} judgeModel={}: {}",
                    systemId, modelId, e.getMessage(), e);
            return new JudgeResult(0.0, modelId, Map.of(),
                    Map.of("error", e.getMessage(), "judgeModel", modelId));
        }
    }

    // ─── Routing ──────────────────────────────────────────────────────────────

    /**
     * Returns the judge model ID for a given system without making any API call.
     * Used by callers that need to persist or log the routing decision upfront.
     */
    public String resolveJudgeModelId(String systemId) {
        return switch (systemId) {
            case "multi-agent"          -> GPT4O_MODEL_ID;   // Claude output → GPT-4o judge
            case "single-prompt-gpt4o"  -> CLAUDE_MODEL_ID;  // GPT-4o output → Claude judge
            case "single-prompt-claude" -> GPT4O_MODEL_ID;   // Claude output → GPT-4o judge
            default -> {
                log.warn("[cross-model-judge] Unknown systemId '{}' — defaulting to GPT-4o judge",
                        systemId);
                yield GPT4O_MODEL_ID;
            }
        };
    }

    private ChatLanguageModel resolveJudge(String systemId) {
        return switch (systemId) {
            case "multi-agent",
                 "single-prompt-claude" -> {
                // Claude generated this → GPT-4o judges; degrade to Claude if GPT-4o absent
                if (gpt4oModel != null) yield gpt4oModel;
                log.warn("[cross-model-judge] GPT-4o absent — falling back to Claude for {}", systemId);
                yield claudeModel;
            }
            case "single-prompt-gpt4o" -> {
                // GPT-4o generated this → Claude judges; degrade to GPT-4o if Claude absent
                if (claudeModel != null) yield claudeModel;
                log.warn("[cross-model-judge] Claude absent — falling back to GPT-4o for {}", systemId);
                yield gpt4oModel;
            }
            default -> gpt4oModel != null ? gpt4oModel : claudeModel;
        };
    }

    public boolean isAvailable() {
        return gpt4oModel != null || claudeModel != null;
    }

    // ─── Internal ─────────────────────────────────────────────────────────────

    private void logRoutingTable() {
        if (gpt4oModel != null && claudeModel != null) {
            log.info("[cross-model-judge] Full cross-model evaluation active:");
            log.info("  multi-agent output        → judged by GPT-4o");
            log.info("  single-prompt-gpt4o output→ judged by Claude");
            log.info("  single-prompt-claude output→ judged by GPT-4o");
        } else if (claudeModel != null) {
            log.warn("[cross-model-judge] DEGRADED — only Claude available (self-scoring for multi-agent)");
        } else if (gpt4oModel != null) {
            log.warn("[cross-model-judge] DEGRADED — only GPT-4o available (self-scoring for gpt4o baseline)");
        } else {
            log.warn("[cross-model-judge] No judge models available — LLM_JUDGE_SCORE will be 0.0");
        }
    }
}
